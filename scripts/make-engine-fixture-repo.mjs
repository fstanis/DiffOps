#!/usr/bin/env bun
// Generates a small synthetic git repository for the in-browser engine check
// (src/standalone/engine-check.html): packed objects and packed refs via
// `git gc`, a symbolic origin/HEAD, a merged feature branch, a rename, a
// whitespace-only change, and staged + unstaged working-tree edits — every
// shape that has broken the wasm engine so far. The real git CLI computes the
// expectations the browser run compares against.
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

const repoDir = process.argv[2] ?? '/tmp/diffops-engine-fixture';
// --loose skips `git gc`: the fixture keeps loose objects and loose refs and
// has no packed-refs, exercising the engine's other read path.
const isLoose = process.argv.includes('--loose');
const WORKING_MARKER = '// UNSTAGED_MARKER';
const WIDE_FILE_COUNT = 30;
const WIDE_FILE_LINES = 300;
// Holds the post-commit `.git` the refresh check mounts; served alongside the
// repository but kept out of its own file list.
const COMMITTED_SNAPSHOT_DIR = 'committed';

// Hermetic config: no user/system git config, fixed identity and dates, so
// the generated hashes are deterministic.
const BASE_ENV = {
  GIT_CONFIG_GLOBAL: '/dev/null',
  GIT_CONFIG_SYSTEM: '/dev/null',
  GIT_AUTHOR_NAME: 'diffops fixture',
  GIT_AUTHOR_EMAIL: 'fixture@diffops.local',
  GIT_COMMITTER_NAME: 'diffops fixture',
  GIT_COMMITTER_EMAIL: 'fixture@diffops.local',
};

let commitIndex = 0;

const gitIn = (dir, args, env = {}) => {
  const date = new Date(Date.parse('2026-01-01T00:00:00Z') + commitIndex * 60_000)
    .toISOString()
    .replace('T', ' ');
  const result = Bun.spawnSync(['git', '-C', dir, ...args], {
    env: {
      ...process.env,
      ...BASE_ENV,
      GIT_AUTHOR_DATE: `${date} +0000`,
      GIT_COMMITTER_DATE: `${date} +0000`,
      ...env,
    },
    stdout: 'pipe',
    stderr: 'pipe',
  });
  if (result.exitCode !== 0) {
    throw new Error(`git -C ${dir} ${args.join(' ')} failed: ${result.stderr.toString()}`);
  }
  return result.stdout.toString().trim();
};

const git = (args, env = {}) => gitIn(repoDir, args, env);

// A `git commit` that also advances the deterministic clock.
const commit = (message) => {
  commitIndex += 1;
  git(['commit', '-m', message]);
  return git(['rev-parse', 'HEAD']);
};

const writeFile = (relativePath, content) => {
  const absolutePath = join(repoDir, relativePath);
  mkdirSync(dirname(absolutePath), { recursive: true });
  writeFileSync(absolutePath, typeof content === 'string' ? content : Buffer.from(content));
};

await (async () => {
  rmSync(repoDir, { recursive: true, force: true });
  mkdirSync(repoDir, { recursive: true });
  git(['init', '-b', 'main']);

  // Untracked trees (node_modules, build output) must never leak into a diff;
  // the .gitignore is tracked so the walker still mounts it.
  writeFile('.gitignore', 'dist/\nnode_modules/\n');
  writeFile(
    'README.md',
    `# engine fixture

Synthetic repository generated by scripts/make-engine-fixture-repo.mjs.
`,
  );
  writeFile(
    'package.json',
    `{
  "name": "engine-fixture",
  "version": "1.0.0",
  "private": true
}
`,
  );
  writeFile('package-lock.json', '{\n  "lockfileVersion": 3\n}\n');
  writeFile('src/app.ts', 'export const run = (): string => {\n  return "v1";\n};\n');
  writeFile(
    'src/util.ts',
    'export const greet = (name: string): string => {\n  return `hi ${name}`;\n};\n',
  );
  writeFile('docs/note.md', 'Notes:\nengine fixture documentation\n');
  // Ends without a trailing newline: `cat-file -p` of this blob leaves lg2's
  // stdout buffer dangling mid-line, which used to contaminate the next git
  // command's output (regression shape for the e2e revision-change spec).
  writeFile('zz-notes.md', 'Fixture notes:\n- trailing newline deliberately omitted');
  // A NUL byte so binary blob handling has something to trip on.
  writeFile('assets/logo.bin', [0x89, 0x50, 0x4e, 0x47, 0x00, 0x0d, 0x0a, 0x1a, 0x0a]);

  git(['add', '.']);
  const setupHash = commit('initial import');

  const hashAfterCommit = [];
  for (let i = 1; i <= 30; i += 1) {
    writeFile('src/app.ts', `export const run = (): string => {\n  return "v${i + 1}";\n};\n`);
    git(['add', 'src/app.ts']);
    hashAfterCommit[i] = commit(`bump app to v${i + 1}`);
  }

  // A merged feature branch: exercises the merge commit and the rev-list
  // intersection the engine uses as its merge-base approximation.
  git(['checkout', '-b', 'feature', hashAfterCommit[10]]);
  const featureHashes = [];
  for (let i = 1; i <= 5; i += 1) {
    writeFile(
      'src/util.ts',
      `export const greet = (name: string): string => {\n  return 'hello ' + name + ' (${i})';\n};\n`,
    );
    git(['add', 'src/util.ts']);
    featureHashes.push(commit(`greeting variant ${i}`));
  }
  git(['checkout', 'main']);
  const mergeBaseCandidate = git(['rev-parse', 'HEAD']);
  git(['merge', '--no-ff', 'feature', '-m', 'merge feature branch']);
  const mergeHash = git(['rev-parse', 'HEAD']);

  const renameBase = git(['rev-parse', 'HEAD']);
  mkdirSync(join(repoDir, 'src/util'), { recursive: true });
  git(['mv', 'src/util.ts', 'src/util/helpers.ts']);
  const renameTarget = commit('move util into util/helpers');

  const whitespaceBase = git(['rev-parse', 'HEAD']);
  writeFile('docs/note.md', 'Notes:   \nengine fixture documentation\n');
  git(['add', 'docs/note.md']);
  const whitespaceTarget = commit('whitespace touch-up');

  // A branch of many long files: the scroll-stability e2e spec needs a diff big
  // enough for files to render lazily and for rows to fall outside the mounted
  // range. It lives off to the side so main's history stays small.
  const wideLine = (index, revision) => {
    if (index % 7 === 0) {
      // Long enough to wrap, so row heights are not uniform.
      return `  const identifier${index} = compute(${index}, { note: 'a string literal long enough that it wraps onto a second visual line at ordinary window widths' });`;
    }
    if (index % 3 === 0) {
      return `  function handler${index}(event: Event): void { dispatch(event); }`;
    }
    return `  const x${index} = ${index};${index % 5 === 1 ? ` // ${revision}` : ''}`;
  };
  const writeWideFiles = (revision) => {
    for (let file = 0; file < WIDE_FILE_COUNT; file += 1) {
      // Zero-padded so git's alphabetical file order matches the numeric one.
      const index = String(file).padStart(2, '0');
      writeFile(
        `src/module${index}/generated${index}.ts`,
        `${Array.from({ length: WIDE_FILE_LINES }, (_, index) => wideLine(index, revision)).join('\n')}\n`,
      );
    }
  };
  git(['checkout', '-b', 'wide', setupHash]);
  writeWideFiles('old');
  git(['add', '.']);
  const wideBase = commit('add generated modules');
  writeWideFiles('new');
  git(['add', '.']);
  const wideTarget = commit('edit generated modules');
  git(['checkout', 'main']);

  // A real submodule in the modern .git-as-a-file layout `git submodule add`
  // produces. The older .git-as-a-directory layout is deliberately NOT in
  // this fixture: under engine-check's unfiltered full mount it emits a
  // spurious "…-dirty" delta (measured — see fastgit.md 1b-bis, table row 3,
  // a pre-existing libgit2 behaviour the tracked walker fixes), which would
  // contradict the real-git-computed expectations. The walker's handling of
  // that layout is covered by walkRepository.test.ts instead.
  const submoduleSourceDir = join(dirname(repoDir), `${basename(repoDir)}-submodule-source`);
  rmSync(submoduleSourceDir, { recursive: true, force: true });
  mkdirSync(submoduleSourceDir, { recursive: true });
  gitIn(submoduleSourceDir, ['init', '-b', 'main']);
  writeFileSync(join(submoduleSourceDir, 'hello.txt'), 'hello from the submodule\n');
  gitIn(submoduleSourceDir, ['add', '.']);
  commitIndex += 1;
  gitIn(submoduleSourceDir, ['commit', '-m', 'submodule initial']);

  // git rejects relative submodule URLs that do not start with ./ or ../, so
  // the source is always registered by its absolute path.
  const submoduleSourceUrl = resolve(submoduleSourceDir);
  git([
    '-c',
    'protocol.file.allow=always',
    'submodule',
    'add',
    '--name',
    'sub',
    submoduleSourceUrl,
    'sub',
  ]);
  commit('add a file-layout submodule');

  // Remote-tracking refs with a symbolic default, exactly like a clone.
  const mainHash = git(['rev-parse', 'main']);
  git(['update-ref', 'refs/remotes/origin/main', mainHash]);
  git(['symbolic-ref', 'refs/remotes/origin/HEAD', 'refs/remotes/origin/main']);

  // Pack everything: packfiles and packed refs are the mmap shapes that
  // WORKERFS could not serve (see docs/plans/pwa-port.md stage 3). --loose
  // keeps the never-gc'd shape instead: loose objects, loose refs, no
  // packed-refs.
  if (!isLoose) {
    git(['gc', '--quiet']);
  }

  writeFile(
    'src/app.ts',
    `export const run = (): string => {\n  return "v31";\n};\n${WORKING_MARKER}\n`,
  );
  writeFile(
    'README.md',
    `# engine fixture

Synthetic repository generated by scripts/make-engine-fixture-repo.mjs.
Staged edit.
`,
  );
  git(['add', 'README.md']);
  writeFile('notes.txt', 'untracked scratch file\n');
  writeFile('node_modules/pkg/index.js', 'export const dependency = (): void => {};\n');
  writeFile('dist/out.txt', 'build output the walker must skip\n');
  writeFile(
    'zz-notes.md',
    'Fixture notes:\n- trailing newline deliberately omitted\n- edited locally',
  );

  const countLines = (value) => {
    const lines = value.split('\n');
    return lines[lines.length - 1] === '' ? lines.length - 1 : lines.length;
  };

  const expected = {
    setupHash,
    mergeBaseCandidate,
    mergeHash,
    featureHash: featureHashes[featureHashes.length - 1],
    pairBase: hashAfterCommit[10],
    pairTarget: hashAfterCommit[20],
    pairChangedFiles: git(['diff', '--name-only', hashAfterCommit[10], hashAfterCommit[20]])
      .split('\n')
      .filter(Boolean).length,
    renameBase,
    renameTarget,
    renamedFrom: 'src/util.ts',
    renamedTo: 'src/util/helpers.ts',
    whitespaceBase,
    whitespaceTarget,
    whitespaceFile: 'docs/note.md',
    wideBase,
    wideTarget,
    wideFileCount: WIDE_FILE_COUNT,
    revCount: Number(git(['rev-list', '--count', 'HEAD'])),
    headHash: git(['rev-parse', 'HEAD']),
    branch: git(['symbolic-ref', '--short', 'HEAD']),
    originDefaultBranch: 'origin/main',
    originMainHash: mainHash,
    workingChangedFiles: git(['diff', '--name-only', 'HEAD']).split('\n').filter(Boolean).length,
    stagedChangedFiles: git(['diff', '--cached', '--name-only', 'HEAD']).split('\n').filter(Boolean)
      .length,
    workingModifiedPath: 'src/app.ts',
    workingMarker: WORKING_MARKER,
    packageJsonLineCount: countLines(git(['show', 'HEAD:package.json'])),
  };

  const walkFiles = (dir, prefix) => {
    const files = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        files.push(...walkFiles(join(dir, entry.name), `${prefix}${entry.name}/`));
      } else {
        files.push(`${prefix}${entry.name}`);
      }
    }
    return files;
  };

  // The `.git` a `git commit` made outside the app leaves behind: new loose
  // objects, a moved branch ref and a rewritten index, none of which a mounted
  // engine has seen. Refreshing onto it is the shape that crashed the wasm
  // heap ("table index is out of bounds"), so the fixture ships it as a second
  // snapshot. The commit runs in a copy, leaving this repository exactly as
  // the expectations above describe it.
  const committedDir = join(repoDir, COMMITTED_SNAPSHOT_DIR);
  rmSync(committedDir, { recursive: true, force: true });
  const commitSourceDir = join(dirname(repoDir), `${basename(repoDir)}-committed-source`);
  rmSync(commitSourceDir, { recursive: true, force: true });
  cpSync(repoDir, commitSourceDir, { recursive: true });
  gitIn(commitSourceDir, ['add', '-A']);
  commitIndex += 1;
  gitIn(commitSourceDir, ['commit', '-m', 'committed outside diffops']);
  expected.committedHead = gitIn(commitSourceDir, ['rev-parse', 'HEAD']);
  mkdirSync(committedDir, { recursive: true });
  cpSync(join(commitSourceDir, '.git'), join(committedDir, '.git'), { recursive: true });

  const manifestPath = join(repoDir, 'manifest.json');
  rmSync(manifestPath, { force: true });

  const files = walkFiles(repoDir, '').filter(
    (path) =>
      path !== 'manifest.json' &&
      !path.startsWith('.DS_Store') &&
      !path.startsWith(`${COMMITTED_SNAPSHOT_DIR}/`),
  );
  const committedFiles = walkFiles(join(committedDir, '.git'), '.git/');

  writeFileSync(
    manifestPath,
    `${JSON.stringify({ repoName: 'engine-fixture', files, committedFiles, expected }, null, 2)}\n`,
  );

  const fileCount = files.filter((path) => path.startsWith('.git/')).length;
  console.log(
    `fixture ready → ${repoDir} (${files.length} files, ${fileCount} under .git, ${expected.revCount} commits, head ${expected.headHash.slice(0, 7)})`,
  );
})();
