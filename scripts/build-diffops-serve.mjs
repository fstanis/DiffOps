#!/usr/bin/env bun
// Builds dist/diffops-serve — the Stage 8 portable artifact: `bun build
// --compile` of the server with the built PWA embedded in the executable.
// Zero dependencies at run time: the binary serves the app and /ai-gateway
// on a machine with nothing installed. Set DIFFOPS_SERVE_TARGET (e.g.
// bun-linux-x64, bun-darwin-arm64, bun-windows-x64) to cross-compile.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = process.cwd();
const pwaDir = resolve(root, 'dist/pwa');
const entryPath = resolve(root, 'dist/diffops-serve.entry.mjs');
const target = process.env.DIFFOPS_SERVE_TARGET ?? null;
const binaryPath = resolve(
  root,
  'dist',
  target?.includes('windows') ? 'diffops-serve.exe' : 'diffops-serve',
);
const bun = process.execPath;

const run = (args) => {
  const result = Bun.spawnSync([bun, ...args], {
    cwd: root,
    env: process.env,
    stdio: ['ignore', 'inherit', 'inherit'],
  });
  if (result.exitCode !== 0) {
    throw new Error(`Command failed: bun ${args.join(' ')}`);
  }
};

// The binary embeds exactly the hashed assets the freshly built shell
// references, so the PWA build runs first.
run(['scripts/build-pwa.mjs']);

const walkFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = join(dir, entry.name);
    return entry.isDirectory() ? walkFiles(fullPath) : [fullPath];
  });

// The binary ships the app and the gateway; the engine-check page, the
// generated fixture tree, and logs are dev-server concerns.
const isEmbeddedAsset = (path) =>
  !path.startsWith('fixture/') && path !== 'engine-check.html' && !path.endsWith('.log');

const relativePaths = walkFiles(pwaDir).map((fullPath) => relative(pwaDir, fullPath));
// Import specifiers in the generated entry must stay URL-safe; build output
// is hash-named, so anything else means an unexpected artifact kind.
for (const path of relativePaths) {
  if (!/^[A-Za-z0-9._/-]+$/.test(path)) {
    throw new Error(`Unexpected character in dist/pwa artifact name: ${path}`);
  }
}
const assetPaths = relativePaths.filter(isEmbeddedAsset).sort();

const entrySource = [
  '// Generated by scripts/build-diffops-serve.mjs — do not edit.',
  "import { startEmbeddedServer } from '../src/server/embeddedServer.ts';",
  ...assetPaths.map(
    (path, index) => `import asset${index} from './pwa/${path}' with { type: 'file' };`,
  ),
  '',
  'startEmbeddedServer(new Map([',
  ...assetPaths.map((path, index) => `  ['/${path}', asset${index}],`),
  ']));',
  '',
].join('\n');
writeFileSync(entryPath, entrySource);

run([
  'build',
  '--compile',
  '--minify',
  ...(target ? ['--target', target] : []),
  entryPath,
  '--outfile',
  binaryPath,
]);

const formatMegabytes = (bytes) => `${(bytes / 1_000_000).toFixed(1)} MB`;
const embeddedBytes = assetPaths.reduce(
  (total, path) => total + statSync(join(pwaDir, path)).size,
  0,
);
console.log(
  `diffops-serve built → ${relative(root, binaryPath)} (${assetPaths.length} embedded PWA files, ` +
    `${formatMegabytes(embeddedBytes)}; binary ${formatMegabytes(statSync(binaryPath).size)})`,
);
